/// <summary>
/// Parity reference generator for the CD64 plugin's C++ port of the N64 audio engine.
/// Runs the real C# (decoder, encoder, processor, synth) on the inputs in
/// imgxtract/plugin/tests/ and writes raw little-endian results + manifest.txt to the
/// reference directory. Test-only: not used by the game, compiled only in editor builds.
/// Entry point: make_reference.gd (run by imgxtract/plugin/tests/make_reference.sh).
/// </summary>

public partial class N64ParityRefGen : RefCounted
{
	private string _out;
	private readonly StringBuilder _manifest = new();

	/// <summary>`testsDir` = imgxtract/plugin/tests (inputs), `outDir` = its reference/ dir.
	/// Returns 0 on success.</summary>
	public int Run(string testsDir, string outDir)
	{
		try
		{
			_out = outDir;
			Directory.CreateDirectory(outDir);
			_manifest.AppendLine("# Generated by N64ParityRefGen.cs (real m3d3 C#). Do not edit.");
			_manifest.AppendLine($"generator.dotnet {System.Environment.Version}");
			_manifest.AppendLine($"generator.arch {RuntimeInformation.ProcessArchitecture}");
			string inputDir = Path.Combine(outDir, "input");

			DecodeCases();
			EncodeCases();
			var procSamples = ProcessorCases(Path.Combine(testsDir, "processor_cases.txt"), inputDir);
			SynthCases(Path.Combine(testsDir, "synth_script.txt"), procSamples);

			File.WriteAllText(Path.Combine(outDir, "manifest.txt"), _manifest.ToString());
			GD.Print($"N64ParityRefGen: wrote {outDir}");
			return 0;
		}
		catch (Exception e)
		{
			GD.PrintErr($"N64ParityRefGen failed: {e}");
			return 1;
		}
	}

	// --- Output helpers -------------------------------------------------------------------

	private void Write<T>(string name, T[] data) where T : struct
	{
		File.WriteAllBytes(Path.Combine(_out, name), MemoryMarshal.AsBytes(data.AsSpan()).ToArray());
	}

	private void Meta(string key, object v) => _manifest.AppendLine($"{key} {Format(v)}");

	private static string Format(object v) => v switch
	{
		float f => $"f32:{BitConverter.SingleToInt32Bits(f):x8}",
		double d => $"f64:{BitConverter.DoubleToInt64Bits(d):x16}",
		bool b => b ? "1" : "0",
		IFormattable x => x.ToString(null, CultureInfo.InvariantCulture),
		_ => v.ToString(),
	};

	private static double D(string s) => double.Parse(s, CultureInfo.InvariantCulture);
	private static int I(string s) => int.Parse(s, CultureInfo.InvariantCulture);

	private static Dictionary<string, string> Kv(string[] tok, int from)
	{
		var d = new Dictionary<string, string>();
		for (int i = from; i < tok.Length; i++)
		{
			int eq = tok[i].IndexOf('=');
			d[tok[i][..eq]] = tok[i][(eq + 1)..];
		}
		return d;
	}

	private static IEnumerable<string[]> Lines(string path)
	{
		foreach (var raw in File.ReadAllLines(path))
		{
			int hash = raw.IndexOf('#');
			var line = (hash >= 0 ? raw[..hash] : raw).Trim();
			if (line.Length > 0)
				yield return line.Split((char[])null, StringSplitOptions.RemoveEmptyEntries);
		}
	}

	// --- Decoder --------------------------------------------------------------------------

	private void DecodeCases()
	{
		// Arbitrary bitstreams + books (scales 0-15, extreme coefficients, clamping, int wrap).
		var rng = new Random(1234);
		var cases = new (string name, int frames, int npred, int coefRange, int extraSamples)[]
		{
			("dec_rand", 400, 16, 4096, -7),
			("dec_wild", 300, 8, 32767, 0),
			("dec_short", 2, 1, 2048, 5),  // fewer bytes than samples: tail stays 0
			("dec_badbook", 60, 3, 4096, 0),  // predictor indices 0-15, book of 3: zero coefficients past it
		};
		foreach (var c in cases)
		{
			int headerPreds = c.name == "dec_badbook" ? 16 : c.npred;
			var data = new byte[c.frames * N64Adpcm.FrameBytes];
			rng.NextBytes(data);
			for (int f = 0; f < c.frames; f++)
				data[f * N64Adpcm.FrameBytes] = (byte)((rng.Next(16) << 4) | rng.Next(headerPreds));
			var book = new int[c.npred * 2];
			for (int i = 0; i < book.Length; i++)
				book[i] = rng.Next(-c.coefRange, c.coefRange + 1);
			int count = c.frames * N64Adpcm.FrameSamples + c.extraSamples;
			var pcm = N64Adpcm.Decode(data, count, book);
			Write($"{c.name}.adpcm", data);
			Write($"{c.name}.book", book);
			Write($"{c.name}.pcm", pcm);
			Meta($"{c.name}.count", count);
		}
		Meta("dec_negative.count", N64Adpcm.Decode(new byte[18], -5, new int[2]).Length);
	}

	// --- Encoder --------------------------------------------------------------------------

	private void EncodeCase(string name, short[] pcm, int predictors)
	{
		var (data, book) = N64AdpcmEncoder.Encode(pcm, predictors);
		Write($"{name}.in", pcm);
		Write($"{name}.adpcm", data);
		Write($"{name}.book", book);
		Meta($"{name}.predictors", predictors);
		Meta($"{name}.count", pcm.Length);
		Meta($"{name}.snr", Snr(pcm, N64Adpcm.Decode(data, pcm.Length, book)));
	}

	private static double Snr(short[] a, short[] b)
	{
		double sig = 0, noise = 0;
		for (int i = 0; i < a.Length; i++)
		{
			sig += (double)a[i] * a[i];
			double d = a[i] - b[i];
			noise += d * d;
		}
		return noise <= 0 ? 99.0 : 10 * Math.Log10(sig / noise);
	}

	private void EncodeCases()
	{
		var rng = new Random(99);
		// Periodic: identical frames give identical predictor vectors (ties in the k-means sort).
		var sine = new short[4000];
		for (int i = 0; i < sine.Length; i++)
			sine[i] = (short)Math.Round(12000 * Math.Sin(2 * Math.PI * i / 32.0) + 3000 * Math.Sin(2 * Math.PI * i / 8.0));
		EncodeCase("enc_sine", sine, 4);
		var noise = new short[3000];
		for (int i = 0; i < noise.Length; i++)
			noise[i] = (short)rng.Next(-32768, 32768);
		EncodeCase("enc_noise", noise, 16);
		var quiet = new short[2000];
		for (int i = 1500; i < quiet.Length; i += 37)
			quiet[i] = (short)rng.Next(-3, 4);
		EncodeCase("enc_quiet", quiet, 4);
		EncodeCase("enc_silence", new short[777], 4);
		EncodeCase("enc_tiny", new short[] { 100, -200, 3000, 32767, -32768 }, 2);
		var chirp = new short[20000];
		for (int i = 0; i < chirp.Length; i++)
		{
			double t = i / 22050.0;
			chirp[i] = (short)Math.Clamp(Math.Round(30000 * Math.Sin(2 * Math.PI * (100 + 2000 * t) * t) * Math.Exp(-t)), -32768, 32767);
		}
		EncodeCase("enc_chirp", chirp, 8);
		EncodeCase("enc_chirp1", chirp, 1);
	}

	// --- Processor ------------------------------------------------------------------------

	private static readonly FieldInfo ProcessedField =
		typeof(N64AudioProcessor).GetField("_processed", BindingFlags.NonPublic | BindingFlags.Instance);

	private Dictionary<string, N64Sample> ProcessorCases(string casesPath, string inputDir)
	{
		var samples = new Dictionary<string, N64Sample>();
		var loaded = new HashSet<string>();
		foreach (var tok in Lines(casesPath))
		{
			if (tok[0] != "case") continue;
			string name = tok[1];
			var kv = Kv(tok, 2);
			string input = kv["input"];
			kv.Remove("input");
			var proc = new N64AudioProcessor();
			string err = proc.LoadWav(Path.Combine(inputDir, input));
			if (err != "") throw new Exception($"{input}: {err}");
			string stem = Path.GetFileNameWithoutExtension(input);
			if (loaded.Add(stem))
			{
				Write($"src_{stem}.f32", proc.Source);
				Meta($"src_{stem}.rate", proc.SourceRate);
				var pitch = proc.DetectPitch();
				Meta($"src_{stem}.pitch_note", pitch[0]);
				Meta($"src_{stem}.pitch_conf", pitch[1]);
				Write($"src_{stem}.pcmbytes", proc.SourcePcmBytes());
				Write($"src_{stem}.waveform", proc.SourceWaveform(97));
			}

			// Shaping keys only when listed: the other cases are "old" dictionaries without them.
			var settings = new Godot.Collections.Dictionary();
			foreach (var (k, v) in kv)
			{
				switch (k)
				{
					case "rate": case "bits": case "predictors": case "root_key":
						settings[k] = I(v); break;
					case "trim": case "normalize":
						settings[k] = I(v) != 0; break;
					case "loop":
						settings[k] = v; break;
					default:
						settings[k] = D(v); break;
				}
			}
			var s = proc.Process(settings);
			var processed = (short[])ProcessedField.GetValue(proc);
			string p = $"proc_{name}";
			Write($"{p}.processed", processed);
			Write($"{p}.adpcm", s.Adpcm);
			Write($"{p}.book", s.Book);
			Write($"{p}.decoded", s.Pcm);
			Meta($"{p}.SampleCount", s.SampleCount);
			Meta($"{p}.SampleRate", s.SampleRate);
			Meta($"{p}.Loop", s.Loop);
			Meta($"{p}.LoopStart", s.LoopStart);
			Meta($"{p}.LoopEnd", s.LoopEnd);
			Meta($"{p}.RootKey", s.RootKey);
			Meta($"{p}.TuneCents", s.TuneCents);
			Meta($"{p}.snr", proc.AdpcmSnr(s));
			samples[name] = s;
		}
		FindLoopCases();
		return samples;
	}

	private static readonly MethodInfo FindLoopMethod =
		typeof(N64AudioProcessor).GetMethod("FindLoop", BindingFlags.NonPublic | BindingFlags.Static);

	/// <summary>FindLoop on hints with no room for its comparison window (used to read before
	/// the sample and throw). Same inputs as tests/test_n64_processor.cpp.</summary>
	private void FindLoopCases()
	{
		var ramp = new short[2000];
		for (int i = 0; i < ramp.Length; i++) ramp[i] = (short)(i * 10);
		var wave = new short[3000];
		for (int i = 0; i < wave.Length; i++) wave[i] = (short)Math.Round(8000 * Math.Sin(2 * Math.PI * i / 50.0));
		var cases = new (string name, short[] x, int hs, int he, int rate)[]
		{
			("ramp", ramp, 0, 1900, 16000),
			("ramp_short", ramp, 0, 100, 16000),
			("ramp_neg", ramp, -50, 1900, 8000),
			("empty", Array.Empty<short>(), 0, 0, 16000),
			("wave_start0", wave, 0, 2900, 16000),
			("wave_end_low", wave, 5, 20, 22050),
		};
		foreach (var c in cases)
		{
			var (ls, le) = ((int, int))FindLoopMethod.Invoke(null, new object[] { c.x, c.hs, c.he, c.rate });
			Meta($"findloop_{c.name}.ls", ls);
			Meta($"findloop_{c.name}.le", le);
		}
	}

	// --- Synth ----------------------------------------------------------------------------

	private void SynthCases(string scriptPath, Dictionary<string, N64Sample> procSamples)
	{
		var bank = new N64SoundBank();
		var bySlot = new Dictionary<int, N64Sample>();
		N64Instrument inst = null;
		List<string[]> script = null;
		string scriptName = null;
		foreach (var tok in Lines(scriptPath))
		{
			if (script != null)
			{
				if (tok[0] == "end")
				{
					RunScript(scriptName, bank, script);
					script = null;
				}
				else script.Add(tok);
				continue;
			}
			switch (tok[0])
			{
				case "sample":
				{
					var s = procSamples[tok[2]];
					if (tok.Length > 3)
					{
						// Damaged copy (bad-data playback cases).
						var d = new N64Sample();
						d.CopyFrom(s);
						foreach (var (k, v) in Kv(tok, 3))
						{
							switch (k)
							{
								case "LoopStart": d.LoopStart = I(v); break;
								case "LoopEnd": d.LoopEnd = I(v); break;
								case "SampleRate": d.SampleRate = I(v); break;
								case "book_pairs": d.Book = d.Book[..(I(v) * 2)]; break;
								default: throw new Exception($"unknown sample field {k}");
							}
						}
						s = d;
					}
					bySlot[I(tok[1])] = s;
					bank.Samples.Add(s);
					break;
				}
				case "inst":
				{
					var kv = Kv(tok, 1);
					inst = new N64Instrument
					{
						Name = kv["name"], Program = I(kv["program"]), Bank = I(kv["bank"]),
						IsDrumKit = I(kv["drum"]) != 0, Volume = (float)D(kv["volume"]), Pan = (float)D(kv["pan"]),
					};
					var e = kv["env"].Split(',');
					inst.Envelope = new Vector4((float)D(e[0]), (float)D(e[1]), (float)D(e[2]), (float)D(e[3]));
					var vb = kv["vib"].Split(',');
					inst.Vibrato = new Vector3((float)D(vb[0]), (float)D(vb[1]), (float)D(vb[2]));
					bank.Instruments.Add(inst);
					break;
				}
				case "zone":
				{
					var z = new Godot.Collections.Dictionary();
					foreach (var (k, v) in Kv(tok, 1))
					{
						if (k == "sample") z[k] = bySlot[I(v)];
						else if (k is "key_lo" or "key_hi" or "vel_lo" or "vel_hi" or "root_key") z[k] = I(v);
						else z[k] = D(v);
					}
					inst.Zones.Add(z);
					break;
				}
				case "script":
					scriptName = tok[1];
					script = new List<string[]>();
					break;
			}
		}
		SequenceGainCheck(bank);
	}

	/// <summary>C#-only (the port has no sequences): an attached sequence's fade scales the
	/// MIDI-channel voices only, never OutputGain or direct (sound effect) voices, and stops
	/// applying once detached. Throws if not.</summary>
	private void SequenceGainCheck(N64SoundBank bank)
	{
		float Peak(N64Synth s, int frames)
		{
			var buf = s.Render(frames);
			float p = 0;
			for (int i = frames / 2; i < frames; i++) p = Math.Max(p, Math.Max(Math.Abs(buf[i].X), Math.Abs(buf[i].Y)));
			return p;
		}
		var synth = new N64Synth { Bank = bank, ReverbLevel = 0 };
		var seq = new N64Sequence();
		seq.Start(synth, null);
		seq.FadeTo(0f, 0.001f);
		synth.AttachSequence(seq);
		synth.NoteOn(0, 60, 100);
		float music = Peak(synth, 4000);
		synth.StopAll(true);
		synth.PlayNote(bank.Instruments[0], 60, 100);
		float sfx = Peak(synth, 4000);
		synth.StopAll(true);
		synth.DetachSequence(seq);
		synth.NoteOn(0, 60, 100);
		float after = Peak(synth, 4000);
		Meta("seqgain.music_faded", music);
		Meta("seqgain.sfx", sfx);
		Meta("seqgain.music_detached", after);
		bool ok = music == 0f && sfx > 0.01f && after > 0.01f && synth.OutputGain == 1f;
		synth.Free();
		if (!ok)
			throw new Exception($"sequence gain check: music {music}, sfx {sfx}, after detach {after}");
	}

	private void RunScript(string name, N64SoundBank bank, List<string[]> cmds)
	{
		var synth = new N64Synth { Bank = bank };
		var outL = new List<float>();
		var outR = new List<float>();
		var active = new List<int>();
		var ids = new List<long>();
		void Append(Vector2[] buf)
		{
			foreach (var v in buf) { outL.Add(v.X); outR.Add(v.Y); }
			active.Add(synth.ActiveVoices());
		}
		foreach (var t in cmds)
		{
			switch (t[0])
			{
				case "noteon": synth.NoteOn(I(t[1]), I(t[2]), I(t[3])); break;
				case "noteoff": synth.NoteOff(I(t[1]), I(t[2])); break;
				case "cc": synth.ControlChange(I(t[1]), I(t[2]), I(t[3])); break;
				case "program": synth.ProgramChange(I(t[1]), I(t[2])); break;
				case "bend": synth.PitchBend(I(t[1]), I(t[2])); break;
				case "play":
					ids.Add(synth.PlayNote(bank.Instruments[I(t[1])], I(t[2]), I(t[3]), (float)D(t[4]), (float)D(t[5])));
					break;
				case "stop": synth.StopNote(ids[I(t[1])]); break;
				case "gain": synth.SetChannelGain(I(t[1]), (float)D(t[2])); break;
				case "reset": synth.ResetChannels(); break;
				case "releaseall": synth.ReleaseAll(); break;
				case "stopall": synth.StopAll(I(t[1]) != 0); break;
				case "set":
				{
					float v = (float)D(t[2]);
					switch (t[1])
					{
						case "MaxVoices": synth.MaxVoices = I(t[2]); break;
						case "MasterVolume": synth.MasterVolume = v; break;
						case "PitchBendRange": synth.PitchBendRange = v; break;
						case "ModWheelDepth": synth.ModWheelDepth = v; break;
						case "ReverbLevel": synth.ReverbLevel = v; break;
						case "RoomSize": synth.RoomSize = v; break;
						case "Damping": synth.Damping = v; break;
						case "DirectReverbSend": synth.DirectReverbSend = v; break;
						case "OutputGain": synth.OutputGain = v; break;
						default: throw new Exception($"unknown param {t[1]}");
					}
					break;
				}
				case "mix":
				{
					var buf = new Vector2[I(t[1])];
					synth.Mix(buf);
					Append(buf);
					break;
				}
				case "render": Append(synth.Render(I(t[1]))); break;
				case "skip":
				{
					var buf = new Vector2[4096];
					for (int left = I(t[1]); left > 0; left -= buf.Length)
						synth.Mix(buf.AsSpan(0, Math.Min(left, buf.Length)));
					active.Add(synth.ActiveVoices());
					break;
				}
				default: throw new Exception($"unknown command {t[0]}");
			}
		}
		Write($"synth_{name}.L.f32", outL.ToArray());
		Write($"synth_{name}.R.f32", outR.ToArray());
		Write($"synth_{name}.active", active.ToArray());
		Write($"synth_{name}.ids", ids.ToArray());
		Meta($"synth_{name}.frames", outL.Count);
		float peak = 0;
		foreach (var v in outL) peak = Math.Max(peak, Math.Abs(v));
		foreach (var v in outR) peak = Math.Max(peak, Math.Abs(v));
		Meta($"synth_{name}.peak", peak);
		synth.Free();
	}
